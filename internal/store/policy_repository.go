// PolicyRepository owns persistence for policy definitions, violations, and
// evaluations.
//
// # Bounded reads
//
// Every list is paginated, every sort field comes from an allowlist, and the
// summary is a handful of aggregate queries rather than a list the caller
// counts. The summary is what a dashboard polls, so it is the one that must not
// become O(violations).
//
// # No N+1
//
// The engine loads every active policy ONCE per sweep through ActivePolicies
// and applies that slice to each container. Nothing in the evaluation path
// queries per container except the single reconcile transaction that writes its
// result.
type PolicyRepository struct {
	db *sql.DB
}

// ErrPolicyNameTaken reports a duplicate policy name.
//
// Names are not identifiers -- the immutable policy id is -- but two policies
// called "Production baseline" make a violation list unreadable, so the name is
// unique among policies that are not archived.
var ErrPolicyNameTaken = errors.New("a policy with that name already exists")

// policySortFields is the allowlist of sortable policy columns.
//
// An allowlist rather than validation-by-rejection: the value becomes part of
// the SQL text, so the only safe design is one where caller input SELECTS from
// a fixed set of literals rather than contributing to it.
var policySortFields = map[string]string{
	"name":      "name",
	"severity":  policySeverityRankSQL,
	"createdAt": "created_at",
	"updatedAt": "updated_at",
	"rules":     "rule_count",
	"id":        "id",
}

// policyViolationSortFields is the allowlist for the violation list.
var policyViolationSortFields = map[string]string{
	"detectedAt": "detected_at",
	"lastSeenAt": "last_seen_at",
	"id":         "id",
	"container":  "container_name",
	"policy":     "policy_name",
	"rule":       "rule_type",
	"status":     "status",
	"severity":   policySeverityRankSQL,
}

// policySeverityRankSQL orders by how much a row matters rather than by the
// spelling of its severity. Built from literals only.
const policySeverityRankSQL = `CASE severity ` +
	`WHEN 'critical' THEN 4 ` +
	`WHEN 'high' THEN 3 ` +
	`WHEN 'medium' THEN 2 ` +
	`WHEN 'low' THEN 1 ` +
	`ELSE 0 END`

// ValidPolicySortField reports whether field names a sortable policy column.
func ValidPolicySortField(field string) bool {
	_, ok := policySortFields[field]
	return ok
}

// ValidPolicyViolationSortField reports whether field names a sortable
// violation column.
func ValidPolicyViolationSortField(field string) bool {
	_, ok := policyViolationSortFields[field]
	return ok
}

// ------------------------------------------------------------ definitions --

// PolicyFilter narrows a policy listing.
type PolicyFilter struct {
	// EnabledOnly restricts to policies that participate in evaluation.
	EnabledOnly bool
	// IncludeArchived includes withdrawn policies. Excluded by default: an
	// archived policy is history, and a list dominated by history buries the
	// rules actually in force.
	IncludeArchived bool
	Search          string

	Sort      string
	Ascending bool
	Page      Page
}

const selectPolicyColumns = `
	SELECT id, policy_id, name, description, severity,
	       enabled, archived, archived_at, rules_json, created_at, updated_at
	FROM policy_definitions`

// CreatePolicy stores a new definition.
//
// The policy id is generated by the caller (domain.NewPolicyID) and is never
// derived from caller input, so a caller cannot choose or collide with one.
func (r *PolicyRepository) CreatePolicy(
	ctx context.Context,
	policy domain.PolicyDefinition,
	now time.Time,
) (domain.PolicyDefinition, error) {
	rules, err := encodePolicyRules(policy.Rules)
	if err != nil {
		return domain.PolicyDefinition{}, err
	}
	stamp := formatTime(now.UTC())

	taken, err := r.nameTaken(ctx, policy.Name, "")
	if err != nil {
		return domain.PolicyDefinition{}, err
	}
	if taken {
		return domain.PolicyDefinition{}, ErrPolicyNameTaken
	}

	enabled := 0
	if policy.Enabled {
		enabled = 1
	}

	result, err := r.db.ExecContext(ctx, `
		INSERT INTO policy_definitions
			(policy_id, name, description, severity, enabled, archived,
			 rules_json, rule_count, created_at, updated_at)
		VALUES (?, ?, ?, ?, ?, 0, ?, ?, ?, ?)`,
		policy.PolicyID, policy.Name, policy.Description, string(policy.Severity),
		enabled, rules, len(policy.Rules), stamp, stamp)
	if err != nil {
		return domain.PolicyDefinition{}, fmt.Errorf("insert policy: %w", AsError(err))
	}

	// Reported for the returned row only; the insert has already succeeded.
	id, _ := result.LastInsertId()
	policy.ID = id
	policy.Archived = false
	policy.CreatedAt = now.UTC()
	policy.UpdatedAt = now.UTC()
	return policy, nil
}

// PolicyUpdate carries the fields an update may change.
//
// PolicyID is deliberately absent: it is immutable, and a struct that cannot
// express the change is a stronger guarantee than a check that rejects it. Each
// field is a pointer so "not supplied" and "supplied as the zero value" stay
// distinguishable -- without that, omitting `enabled` would silently disable a
// policy.
type PolicyUpdate struct {
	Name        *string
	Description *string
	Severity    *domain.PolicySeverity
	Enabled     *bool
	Rules       *[]domain.PolicyRule
}

// UpdatePolicy applies an update and returns the stored definition.
//
// When the update leaves the policy inactive, its open violations are resolved
// in the SAME transaction. A rule that no longer applies must not keep a row on
// the dashboard until the next sweep happens to notice.
func (r *PolicyRepository) UpdatePolicy(
	ctx context.Context,
	policyID string,
	update PolicyUpdate,
	now time.Time,
) (domain.PolicyDefinition, error) {
	stamp := formatTime(now.UTC())

	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return domain.PolicyDefinition{}, fmt.Errorf("begin policy update: %w", AsError(err))
	}
	defer func() { _ = tx.Rollback() }()

	existing, err := scanPolicyRow(tx.QueryRowContext(ctx, selectPolicyColumns+` WHERE policy_id = ?`, policyID))
	if err != nil {
		return domain.PolicyDefinition{}, err
	}
	// An archived policy is history. Editing one would change what a violation
	// row appears to have been measured against.
	if existing.Archived {
		return domain.PolicyDefinition{}, ErrNotFound
	}

	updated := existing
	if update.Name != nil {
		updated.Name = *update.Name
	}
	if update.Description != nil {
		updated.Description = *update.Description
	}
	if update.Severity != nil {
		updated.Severity = *update.Severity
	}
	if update.Enabled != nil {
		updated.Enabled = *update.Enabled
	}
	if update.Rules != nil {
		updated.Rules = *update.Rules
	}

	if updated.Name != existing.Name {
		taken, checkErr := txNameTaken(ctx, tx, updated.Name, policyID)
		if checkErr != nil {
			return domain.PolicyDefinition{}, checkErr
		}
		if taken {
			return domain.PolicyDefinition{}, ErrPolicyNameTaken
		}
	}

	rules, err := encodePolicyRules(updated.Rules)
	if err != nil {
		return domain.PolicyDefinition{}, err
	}
	enabled := 0
	if updated.Enabled {
		enabled = 1
	}

	if _, err := tx.ExecContext(ctx, `
		UPDATE policy_definitions
		SET name = ?, description = ?, severity = ?, enabled = ?,
		    rules_json = ?, rule_count = ?, updated_at = ?
		WHERE policy_id = ?`,
		updated.Name, updated.Description, string(updated.Severity), enabled,
		rules, len(updated.Rules), stamp, policyID,
	); err != nil {
		return domain.PolicyDefinition{}, fmt.Errorf("update policy: %w", AsError(err))
	}

	// The name is denormalised onto every violation so a list needs no join;
	// a rename must therefore reach them, or the dashboard would keep showing
	// the old one indefinitely.
	if updated.Name != existing.Name {
		if _, err := tx.ExecContext(ctx,
			`UPDATE policy_violations SET policy_name = ?, updated_at = ? WHERE policy_id = ?`,
			updated.Name, stamp, policyID); err != nil {
			return domain.PolicyDefinition{}, fmt.Errorf("rename policy violations: %w", AsError(err))
		}
	}

	if !updated.Active() {
		if _, err := resolveViolationsForPolicy(ctx, tx, policyID, stamp); err != nil {
			return domain.PolicyDefinition{}, err
		}
	}

	if err := tx.Commit(); err != nil {
		return domain.PolicyDefinition{}, fmt.Errorf("commit policy update: %w", AsError(err))
	}

	updated.UpdatedAt = now.UTC()
	return updated, nil
}

// ArchivePolicy withdraws a policy without destroying it.
//
// This is what DELETE /policies/{id} does, and the difference matters:
// policy_violations references this row, and the history must survive the rule
// being withdrawn. An auditor asking what the estate was failing last quarter
// must not get a different answer because someone tidied up this quarter.
//
// The policy's open violations are resolved in the same transaction, because
// the rule no longer applies and a resolved violation is the truthful record of
// that.
func (r *PolicyRepository) ArchivePolicy(ctx context.Context, policyID string, now time.Time) error {
	stamp := formatTime(now.UTC())

	tx, err := r.db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("begin policy archive: %w", AsError(err))
	}
	defer func() { _ = tx.Rollback() }()

	result, err := tx.ExecContext(ctx, `
		UPDATE policy_definitions
		SET archived = 1, archived_at = ?, updated_at = ?
		WHERE policy_id = ? AND archived = 0`, stamp, stamp, policyID)
	if err != nil {
		return fmt.Errorf("archive policy: %w", AsError(err))
	}
	affected, err := result.RowsAffected()
	if err == nil && affected == 0 {
		return ErrNotFound
	}

	if _, err := resolveViolationsForPolicy(ctx, tx, policyID, stamp); err != nil {
		return err
	}

	if err := tx.Commit(); err != nil {
		return fmt.Errorf("commit policy archive: %w", AsError(err))
	}
	return nil
}

// resolveViolationsForPolicy closes every open violation belonging to a policy.
func resolveViolationsForPolicy(ctx context.Context, tx *sql.Tx, policyID, stamp string) (int64, error) {
	result, err := tx.ExecContext(ctx, `
		UPDATE policy_violations
		SET status = 'resolved', resolved_at = ?, updated_at = ?
		WHERE policy_id = ? AND status <> 'resolved'`, stamp, stamp, policyID)
	if err != nil {
		return 0, fmt.Errorf("resolve policy violations: %w", AsError(err))
	}
	// Used for a log line only; the update has already been applied.
	affected, _ := result.RowsAffected()
	return affected, nil
}

// GetPolicy returns one definition by its immutable id.
func (r *PolicyRepository) GetPolicy(ctx context.Context, policyID string) (domain.PolicyDefinition, error) {
	return scanPolicyRow(r.db.QueryRowContext(ctx, selectPolicyColumns+` WHERE policy_id = ?`, policyID))
}

// ListPolicies returns a page of definitions and the total matching the filter.
func (r *PolicyRepository) ListPolicies(
	ctx context.Context,
	filter PolicyFilter,
) ([]domain.PolicyDefinition, int, error) {
	where, args := policyWhere(filter)

	var total int
	if err := r.db.QueryRowContext(ctx,
		`SELECT COUNT(*) FROM policy_definitions`+where, args...).Scan(&total); err != nil {
		return nil, 0, fmt.Errorf("count policies: %w", AsError(err))
	}

	column, ok := policySortFields[filter.Sort]
	if !ok {
		column = "name"
	}
	direction := "DESC"
	if filter.Ascending {
		direction = "ASC"
	}

	page := filter.Page.normalise()
	// column and direction come from the allowlist above and a two-valued
	// switch; neither is caller text. Every VALUE is bound.
	query := selectPolicyColumns + where +
		` ORDER BY ` + column + ` ` + direction + `, id ` + direction +
		` LIMIT ? OFFSET ?`

	rows, err := r.db.QueryContext(ctx, query, append(args, page.Limit, page.Offset)...)
	if err != nil {
		return nil, 0, fmt.Errorf("query policies: %w", AsError(err))
	}
	defer func() { _ = rows.Close() }()

	policies, err := scanPolicies(rows)
	if err != nil {
		return nil, 0, err
	}
	return policies, total, nil
}

// ActivePolicies returns every policy that participates in evaluation.
//
// ONE query for the whole engine. The sweep loads this slice once and applies
// it to every container, which is what keeps a thousand-container pass from
// becoming a thousand policy queries.
//
// Unpaginated by design: the number of policies is bounded by configuration and
// is small by nature. A limit is applied anyway, as a backstop against a
// database that somehow holds more than the API would have accepted.
func (r *PolicyRepository) ActivePolicies(ctx context.Context, limit int) ([]domain.PolicyDefinition, error) {
	if limit < 1 {
		limit = 1000
	}
	rows, err := r.db.QueryContext(ctx,
		selectPolicyColumns+` WHERE archived = 0 AND enabled = 1 ORDER BY id ASC LIMIT ?`, limit)
	if err != nil {
		return nil, fmt.Errorf("query active policies: %w", AsError(err))
	}
	defer func() { _ = rows.Close() }()
	return scanPolicies(rows)
}

// CountPolicies returns the number of active and of total definitions.
func (r *PolicyRepository) CountPolicies(ctx context.Context) (active, total int, err error) {
	if err := r.db.QueryRowContext(ctx, `
		SELECT COALESCE(SUM(CASE WHEN archived = 0 AND enabled = 1 THEN 1 ELSE 0 END), 0),
		       COUNT(*)
		FROM policy_definitions`).Scan(&active, &total); err != nil {
		return 0, 0, fmt.Errorf("count policies: %w", AsError(err))
	}
	return active, total, nil
}

// nameTaken reports whether an unarchived policy already uses the name.
func (r *PolicyRepository) nameTaken(ctx context.Context, name, excluding string) (bool, error) {
	var count int
	err := r.db.QueryRowContext(ctx, `
		SELECT COUNT(*) FROM policy_definitions
		WHERE archived = 0 AND name = ? AND policy_id <> ?`, name, excluding).Scan(&count)
	if err != nil {
		return false, fmt.Errorf("check policy name: %w", AsError(err))
	}
	return count > 0, nil
}

// txNameTaken is nameTaken inside an open transaction.
func txNameTaken(ctx context.Context, tx *sql.Tx, name, excluding string) (bool, error) {
	var count int
	err := tx.QueryRowContext(ctx, `
		SELECT COUNT(*) FROM policy_definitions
		WHERE archived = 0 AND name = ? AND policy_id <> ?`, name, excluding).Scan(&count)
	if err != nil {
		return false, fmt.Errorf("check policy name: %w", AsError(err))
	}
	return count > 0, nil
}

// policyWhere builds the definition filter clause. Every value is bound.
func policyWhere(filter PolicyFilter) (string, []any) {
	clauses := make([]string, 0, 3)
	args := make([]any, 0, 3)

	if !filter.IncludeArchived {
		clauses = append(clauses, "archived = 0")
	}
	if filter.EnabledOnly {
		clauses = append(clauses, "enabled = 1")
	}
	if filter.Search != "" {
		// LIKE with a bound parameter. The wildcards are part of the BOUND
		// VALUE rather than of the SQL text, so a search term containing % or _
		// widens only its own match and cannot alter the statement.
		clauses = append(clauses, "(name LIKE ? ESCAPE '\\' OR description LIKE ? ESCAPE '\\')")
		pattern := "%" + escapeLikePattern(filter.Search) + "%"
		args = append(args, pattern, pattern)
	}

	if len(clauses) == 0 {
		return "", args
	}
	return " WHERE " + strings.Join(clauses, " AND "), args
}

// escapeLikePattern neutralises LIKE metacharacters in a search term.
//
// Without it, a search for "100%" matches every policy, which is a correctness
// bug rather than a security one -- but a term of many '%' characters also
// makes the match itself expensive, which is not.
func escapeLikePattern(term string) string {
	replacer := strings.NewReplacer(`\`, `\\`, `%`, `\%`, `_`, `\_`)
	return replacer.Replace(term)
}

// encodePolicyRules renders the rule list for storage.
func encodePolicyRules(rules []domain.PolicyRule) (string, error) {
	if rules == nil {
		rules = []domain.PolicyRule{}
	}
	encoded, err := json.Marshal(rules)
	if err != nil {
		return "", fmt.Errorf("encode policy rules: %w", err)
	}
	return string(encoded), nil
}

// policyScanner is satisfied by both *sql.Row and *sql.Rows.
type policyScanner interface {
	Scan(dest ...any) error
}

// scanPolicyRow reads one definition.
func scanPolicyRow(row policyScanner) (domain.PolicyDefinition, error) {
	var (
		policy     domain.PolicyDefinition
		severity   string
		enabled    int
		archived   int
		archivedAt sql.NullString
		rules      string
		created    string
		updated    string
	)
	err := row.Scan(&policy.ID, &policy.PolicyID, &policy.Name, &policy.Description,
		&severity, &enabled, &archived, &archivedAt, &rules, &created, &updated)
	if errors.Is(err, sql.ErrNoRows) {
		return domain.PolicyDefinition{}, ErrNotFound
	}
	if err != nil {
		return domain.PolicyDefinition{}, fmt.Errorf("scan policy: %w", AsError(err))
	}

	policy.Severity = domain.PolicySeverity(severity)
	policy.Enabled = enabled == 1
	policy.Archived = archived == 1

	if err := json.Unmarshal([]byte(rules), &policy.Rules); err != nil {
		return domain.PolicyDefinition{}, fmt.Errorf("decode policy rules: %w", err)
	}
	if policy.Rules == nil {
		policy.Rules = []domain.PolicyRule{}
	}

	if policy.CreatedAt, err = parseTime(created); err != nil {
		return domain.PolicyDefinition{}, err
	}
	if policy.UpdatedAt, err = parseTime(updated); err != nil {
		return domain.PolicyDefinition{}, err
	}
	if archivedAt.Valid && archivedAt.String != "" {
		parsed, parseErr := parseTime(archivedAt.String)
		if parseErr != nil {
			return domain.PolicyDefinition{}, parseErr
		}
		policy.ArchivedAt = &parsed
	}
	return policy, nil
}

func scanPolicies(rows *sql.Rows) ([]domain.PolicyDefinition, error) {
	policies := make([]domain.PolicyDefinition, 0, 16)
	for rows.Next() {
		policy, err := scanPolicyRow(rows)
		if err != nil {
			return nil, err
		}
		policies = append(policies, policy)
	}
	return policies, rows.Err()
}

